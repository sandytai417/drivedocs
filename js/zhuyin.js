/**
 * Get 注音 initial for a Chinese character / name.
 * @param {string} name
 * @return {string}
 */
function getZhuyinInitial(name) {
  if (!name || !String(name).trim()) return '#';
  var ch = String(name).trim().charAt(0);
  if (SURNAME_ZHUYIN[ch]) return SURNAME_ZHUYIN[ch];
  if (GIVEN_ZHUYIN[ch]) return GIVEN_ZHUYIN[ch];
  // Latin / digit fallback
  if (/[A-Za-z]/.test(ch)) return '#';
  if (/[0-9]/.test(ch)) return '#';
  return '#';
}

/**
 * Zhuyin of the given-name first character (第 2 字), for tie-break after surname.
 * @param {string} fullName
 * @return {string}
 */
function getGivenNameZhuyin(fullName) {
  var n = String(fullName || '').trim();
  if (n.length < 2) return '#';
  return getZhuyinInitial(n.charAt(1));
}

/**
 * Zhuyin order index (lower = earlier).
 * @param {string} initial
 * @return {number}
 */
function zhuyinIndex(initial) {
  var i = ZHUYIN_ORDER.indexOf(initial);
  return i === -1 ? ZHUYIN_ORDER.length : i;
}

/**
 * Compare two customer names by 教育部注音排序.
 * Same initial → second char → third → full name.
 * @param {string} a
 * @param {string} b
 * @return {number}
 */
function compareByZhuyin(a, b) {
  var na = String(a || '').trim();
  var nb = String(b || '').trim();
  // 1) 姓氏注音
  var di = zhuyinIndex(getZhuyinInitial(na)) - zhuyinIndex(getZhuyinInitial(nb));
  if (di !== 0) return di;
  // 2) 同姓內：名字第一字注音
  var dg = zhuyinIndex(getGivenNameZhuyin(na)) - zhuyinIndex(getGivenNameZhuyin(nb));
  if (dg !== 0) return dg;
  // 3) 其餘字元依注音，再比完整姓名
  var len = Math.max(na.length, nb.length);
  for (var i = 2; i < len; i++) {
    var ca = na.charAt(i) || '';
    var cb = nb.charAt(i) || '';
    if (ca === cb) continue;
    var dz = zhuyinIndex(getZhuyinInitial(ca)) - zhuyinIndex(getZhuyinInitial(cb));
    if (dz !== 0) return dz;
    if (ca < cb) return -1;
    if (ca > cb) return 1;
  }
  return na.localeCompare(nb, 'zh-Hant');
}

/**
 * Sort customers by zhuyin and group by initial.
 * @param {Array<Object>} customers
 * @return {Array<{initial: string, customers: Array<Object>}>}
 */
function groupByZhuyin(customers) {
  var sorted = customers.slice().sort(function (a, b) {
    return compareByZhuyin(a.name, b.name);
  });
  var groups = [];
  var map = {};
  sorted.forEach(function (c) {
    var ini = getZhuyinInitial(c.name);
    if (!map[ini]) {
      map[ini] = { initial: ini, customers: [] };
      groups.push(map[ini]);
    }
    map[ini].customers.push(c);
  });
  groups.sort(function (a, b) {
    return zhuyinIndex(a.initial) - zhuyinIndex(b.initial);
  });
  return groups;
}


